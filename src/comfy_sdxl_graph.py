_UNSET_STRINGS = {"", "default", "auto", "none", "null", "undefined", "n/a"}
_ANNOTATION_RE = re.compile(r"\s*\[(\w+)\]\s*$")
_CKPT_LOADER_CLASSES = ("CheckpointLoaderSimple", "CheckpointLoader", "unCLIPCheckpointLoader")
_CKPT_EXT_RE = re.compile(r"\.(safetensors|ckpt|pt|pth|bin|sft)$", re.I)
_TEMPLATE_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{1,63}$")


def is_unset(value: Any) -> bool:
    return value is None or (isinstance(value, str) and value.strip().lower() in _UNSET_STRINGS)


def _like_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def _truncate(text: str, limit: int) -> str:
    text = text or ""
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "\N{HORIZONTAL ELLIPSIS}"


def validate_template_name(name: str) -> str:
    normalized = (name or "").strip().lower()
    if not _TEMPLATE_NAME_RE.match(normalized):
        raise ValueError(
            f"Invalid workflow template name {name!r}: use 2-64 lowercase letters, digits, "
            "underscores or hyphens, starting with a letter or digit."
        )
    return normalized


def validate_placeholders(graph: Dict[str, Any], placeholders: Dict[str, Any]) -> Dict[str, List[str]]:
    """
    placeholders: {param_name: [node_id, input_name]}. Every entry must point at a literal
    (non-link) input that actually exists in this graph - the same shape apply_overrides() later
    relies on to safely mutate a copy of the stored graph. Returns a normalized copy (string ids).
    """
    normalized: Dict[str, List[str]] = {}
    for param_name, loc in placeholders.items():
        if not (isinstance(loc, (list, tuple)) and len(loc) == 2):
            raise ValueError(f"placeholders[{param_name!r}] must be a [node_id, input_name] pair.")
        node_id, input_name = str(loc[0]), str(loc[1])
        node = graph.get(node_id)
        if node is None:
            raise ValueError(f"placeholders[{param_name!r}] refers to node {node_id!r}, which isn't in this graph.")
        inputs = node.get("inputs") or {}
        if input_name not in inputs:
            raise ValueError(f"placeholders[{param_name!r}] refers to input {input_name!r} on node {node_id!r}, which has no such input.")
        if isinstance(inputs[input_name], list):
            raise ValueError(f"placeholders[{param_name!r}] points at {node_id}.{input_name}, which is wired to another node's output, not a literal value.")
        normalized[str(param_name)] = [node_id, input_name]
    return normalized


def apply_overrides(graph: Dict[str, Any], placeholders: Dict[str, List[str]], overrides: Dict[str, Any]) -> None:
    """Mutates graph in place, setting each override's literal value at its registered placeholder."""
    unknown = [k for k in overrides if k not in placeholders]
    if unknown:
        available = sorted(placeholders.keys()) or ["(this template has no overridable parameters)"]
        raise ValueError(f"Unknown override(s) {unknown} for this template; available parameters are: {available}.")
    for param_name, value in overrides.items():
        node_id, input_name = placeholders[param_name]
        node = graph.get(node_id)
        if node is None or input_name not in (node.get("inputs") or {}):
            raise ValueError(
                f"Stored placeholder for {param_name!r} ({node_id}.{input_name}) no longer matches this "
                "template's graph; re-save it with save_workflow."
            )
        node["inputs"][input_name] = value


def resolve_server(
    requested: Optional[str], default: str, allowed: List[str], allow_unlisted: bool = False
) -> str:
    allowed_norm = [s.rstrip("/") for s in allowed]
    if is_unset(requested):
        return default.rstrip("/")

    wanted = requested.strip()
    if wanted.endswith("/") and not wanted.endswith("://"):
        wanted = wanted[:-1]
    if wanted in allowed_norm:
        return wanted

    with_scheme = wanted if "://" in wanted else f"http://{wanted}"
    parsed = urllib.parse.urlparse(with_scheme)
    for server in allowed_norm:
        s = urllib.parse.urlparse(server)
        if parsed.hostname == s.hostname and (parsed.port is None or parsed.port == s.port):
            return server

    if allow_unlisted:
        if parsed.scheme not in ("http", "https") or not parsed.hostname:
            raise ValueError(f"gpu_server {requested!r} is not a valid http(s) address.")
        try:
            port = parsed.port
        except ValueError:
            raise ValueError(f"gpu_server {requested!r} has an invalid port.") from None
        host = f"[{parsed.hostname}]" if ":" in parsed.hostname else parsed.hostname
        return f"{parsed.scheme}://{host}:{port or 8188}"

    raise ValueError(
        f"Unknown gpu_server {requested!r}. Omit it to use the default, choose one of {allowed_norm}, "
        "or enable the ALLOW_UNLISTED_SERVERS valve."
    )


def parse_source_image(ref: str) -> "tuple[str, str]":
    text = (ref or "").strip()
    md = re.search(r"\((https?://[^)\s]+)\)", text)
    if md:
        text = md.group(1)
    if text.startswith(("http://", "https://")):
        query = urllib.parse.parse_qs(urllib.parse.urlparse(text).query)
        filename = (query.get("filename") or [""])[0]
        if not filename:
            raise ValueError("source_image URL has no 'filename' parameter.")
        if (query.get("type") or ["output"])[0] != "output":
            raise ValueError("source_image must be in the ComfyUI output folder.")
        subfolder = (query.get("subfolder") or [""])[0]
        text = f"{subfolder}/{filename}" if subfolder else filename
    annotation = _ANNOTATION_RE.search(text)
    if annotation:
        if annotation.group(1) != "output":
            raise ValueError("source_image must be in the ComfyUI output folder.")
        text = text[: annotation.start()]
    text = text.replace("\\", "/").strip("/")
    parts = text.split("/")
    if not text or ".." in parts:
        raise ValueError(f"Invalid source_image: {ref!r}")
    return "/".join(parts[:-1]), parts[-1]


def normalize_source_image(ref: str) -> str:
    subfolder, filename = parse_source_image(ref)
    return f"{subfolder}/{filename} [output]" if subfolder else f"{filename} [output]"


def _ckpt_basename(name: str) -> str:
    return name.replace("\\", "/").rsplit("/", 1)[-1]


def _ckpt_key(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", _CKPT_EXT_RE.sub("", _ckpt_basename(name)).lower())


def resolve_checkpoint(requested: str, available: List[str]) -> str:
    """Same matching generate_image uses: exact, case/slash-insensitive, same basename, unique fuzzy match."""
    if requested in available:
        return requested
    norm = requested.replace("\\", "/").strip().lower()
    for a in available:
        if a.replace("\\", "/").lower() == norm:
            return a
    base = _ckpt_basename(requested).strip().lower()
    same_base = [a for a in available if _ckpt_basename(a).lower() == base]
    if len(same_base) == 1:
        return same_base[0]
    key = _ckpt_key(requested)
    fuzzy = [a for a in available if key and key in _ckpt_key(a)]
    if not same_base and len(fuzzy) == 1:
        return fuzzy[0]
    ambiguous = same_base or fuzzy
    if ambiguous:
        raise ValueError(f"Checkpoint {requested!r} is ambiguous on this server; could be any of: {sorted(ambiguous)}.")
    shown = sorted(available)[:80]
    more = f" (+{len(available) - 80} more)" if len(available) > 80 else ""
    raise ValueError(f"Checkpoint {requested!r} was not found on this server. Available: {shown}{more}.")


def format_execution_error(status: Dict[str, Any]) -> str:
    for name, data in status.get("messages", []):
        if name == "execution_error":
            return f"{data.get('node_type', 'node')} {data.get('node_id', '?')}: {data.get('exception_message', 'execution failed')}".strip()
    return "ComfyUI reported an execution error."


def _format_prompt_error(body: Dict[str, Any]) -> str:
    parts = []
    err = body.get("error")
    if isinstance(err, dict):
        parts.append(err.get("message") or err.get("type") or "prompt rejected")
        if err.get("details"):
            parts.append(str(err["details"]))
    elif err:
        parts.append(str(err))
    for node_id, info in (body.get("node_errors") or {}).items():
        for e in info.get("errors", []):
            parts.append(f"node {node_id} ({info.get('class_type', '?')}): {e.get('message', '')} {e.get('details', '')}".strip())
    return "; ".join(p for p in parts if p) or "ComfyUI rejected the prompt."


