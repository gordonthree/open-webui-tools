def extract_prompts(graph: Dict[str, Any]) -> "tuple[Optional[str], Optional[str]]":
    """
    Best-effort positive/negative prompt text for the job database's prompts table (so custom
    graphs are searchable the same way generate_image's are). Only follows the common KSampler
    -> CLIPTextEncode wiring; returns (None, None) for anything else rather than guessing.
    """
    sampler = next((n for n in graph.values() if n.get("class_type") in ("KSampler", "KSamplerAdvanced")), None)
    if not sampler:
        return None, None

    def _text(link: Any) -> Optional[str]:
        if isinstance(link, list) and len(link) == 2:
            target = graph.get(str(link[0])) or {}
            text = (target.get("inputs") or {}).get("text")
            return text if isinstance(text, str) else None
        return None

    inputs = sampler.get("inputs") or {}
    return _text(inputs.get("positive")), _text(inputs.get("negative"))


def parse_workflow(workflow: Any) -> Dict[str, Any]:
    """Accept a JSON string or a dict; return the graph as a dict of node_id -> node."""
    if isinstance(workflow, str):
        try:
            graph = json.loads(workflow)
        except ValueError as e:
            raise ValueError(f"workflow is not valid JSON: {e}") from e
    else:
        graph = workflow
    if not isinstance(graph, dict) or not graph:
        raise ValueError("workflow must be a non-empty JSON object of node_id -> {class_type, inputs}, ComfyUI's API/export format.")
    for node_id, node in graph.items():
        if not isinstance(node, dict) or "class_type" not in node:
            raise ValueError(f"Node {node_id!r} is missing 'class_type'. Every node needs {{'class_type': ..., 'inputs': {{...}}}}.")
        node.setdefault("inputs", {})
    return graph


def validate_graph_shape(graph: Dict[str, Any]) -> None:
    """The two structural checks every graph needs, whether it's about to be submitted
    (prepare_graph) or saved as a template (save_workflow) for later reuse."""
    if SOURCE_IMAGE_NODE_ID in graph:
        raise ValueError(
            f"Node id {SOURCE_IMAGE_NODE_ID!r} is reserved by this tool for the fixed source-image "
            "node; use a different id for your own nodes."
        )
    if not any(n.get("class_type") == "SaveImage" for n in graph.values()):
        raise ValueError(
            "The graph has no SaveImage node, so nothing would land in the server's output folder. "
            "Add a SaveImage node fed from your final IMAGE output."
        )


def prepare_graph(
    graph: Dict[str, Any], filename_prefix: str, source_image_ref: Optional[str]
) -> "tuple[Dict[str, Any], bool]":
    """
    Validate the graph and inject the fixed source-image node. Returns (graph, needs_placeholder).
    Raises ValueError for anything the model needs to fix before submission.
    """
    validate_graph_shape(graph)
    save_nodes = [n for n in graph.values() if n.get("class_type") == "SaveImage"]
    for node in save_nodes:
        node["inputs"].setdefault("filename_prefix", filename_prefix)

    needs_placeholder = is_unset(source_image_ref)
    annotated = f"{PLACEHOLDER_FILENAME} [output]" if needs_placeholder else normalize_source_image(source_image_ref)
    graph[SOURCE_IMAGE_NODE_ID] = {"class_type": "LoadImageOutput", "inputs": {"image": annotated}}
    return graph, needs_placeholder


