@contextlib.contextmanager
def _write_txn(conn: sqlite3.Connection):
    conn.execute("BEGIN IMMEDIATE")
    try:
        yield
    except BaseException:
        conn.execute("ROLLBACK")
        raise
    else:
        conn.execute("COMMIT")


def _now_iso() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def _migrate_authors(conn: sqlite3.Connection) -> None:
    """Bring a database created before authors existed up to date, and make sure author #1 exists.

    The author_id columns are nullable (SQLite requires a NULL default when adding a column that
    has a REFERENCES clause), which also keeps an older copy of the tool, one that doesn't know
    about authors, able to write to an upgraded database - its rows just have no author. Only
    rows that were already there when the column was added are attributed to author #1; later
    NULLs are never rewritten. Done in one write transaction so two processes can't both ALTER."""
    with _write_txn(conn):
        added = []
        for table in ("note_id", "note_data"):
            if "author_id" not in [r["name"] for r in conn.execute(f"PRAGMA table_info({table})")]:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN author_id INTEGER REFERENCES note_author(author_id)")
                added.append(table)
        conn.execute(
            "INSERT INTO note_author (author_id, author_name, created_at) SELECT 1, ?, ? WHERE NOT EXISTS (SELECT 1 FROM note_author)",
            (LEGACY_AUTHOR, _now_iso()),
        )
        for table in added:
            conn.execute(f"UPDATE {table} SET author_id = 1")


def _migrate_chains(conn: sqlite3.Connection) -> None:
    """Add note_data.chain_id (nullable, so an older copy of the tool can still write to the database): the entry_no of the
    first piece of a long text saved with continues=true, shared by all its pieces. v1.7.x marked pieces with a trailing
    ' [continues at entry #N]' in the text instead; when the column is first added, turn those into chains and strip the marker."""
    with _write_txn(conn):
        if "chain_id" in [r["name"] for r in conn.execute("PRAGMA table_info(note_data)")]:
            return
        conn.execute("ALTER TABLE note_data ADD COLUMN chain_id INTEGER")
        chain: Dict[Any, int] = {}
        for r in conn.execute("SELECT note_pk, entry_no, note_text FROM note_data ORDER BY note_pk, entry_no").fetchall():
            m = re.search(r" \[continues at entry #(\d+)\]$", r["note_text"])
            if not m:
                continue
            first = chain.get((r["note_pk"], r["entry_no"]), r["entry_no"])
            chain[(r["note_pk"], r["entry_no"])] = first
            chain[(r["note_pk"], int(m.group(1)))] = first
            conn.execute("UPDATE note_data SET note_text = ? WHERE note_pk = ? AND entry_no = ?", (r["note_text"][: m.start()], r["note_pk"], r["entry_no"]))
        for (note_pk, entry_no), first in chain.items():
            conn.execute("UPDATE note_data SET chain_id = ? WHERE note_pk = ? AND entry_no = ?", (first, note_pk, entry_no))


def _migrate_scores(conn: sqlite3.Connection) -> None:
    """Add the popularity counters (note_id.hits, note_data.hits) and note_data.weight to a database made before them. All are
    NOT NULL with a default, so an older copy of the tool that doesn't know about them can still insert rows."""
    with _write_txn(conn):
        for table, column, ddl in (("note_id", "hits", HITS_DDL), ("note_data", "hits", HITS_DDL), ("note_data", "weight", WEIGHT_DDL)):
            if column not in [r["name"] for r in conn.execute(f"PRAGMA table_info({table})")]:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")


def _migrate_pinned(conn: sqlite3.Connection) -> None:
    """Add note_data.pinned: NULL for an ordinary entry, 1 for one its owner pinned (set only from the web interface, never by a model).
    Nullable with no default, so an older copy of the tool can still insert rows."""
