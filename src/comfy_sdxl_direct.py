def _format_prompt_error(body: Dict[str, Any]) -> str:
    """Turn a ComfyUI /prompt 400 body into something a model (or human) can act on."""
    parts = []
    err = body.get("error")
    if isinstance(err, dict):
        parts.append(err.get("message") or err.get("type") or "prompt rejected")
        if err.get("details"):
            parts.append(str(err["details"]))
    elif err:
        parts.append(str(err))
    for node_id, info in (body.get("node_errors") or {}).items():
        for e in info.get("errors", []):
            parts.append(
                f"node {node_id} ({info.get('class_type', '?')}): "
                f"{e.get('message', '')} {e.get('details', '')}".strip()
            )
    return "; ".join(p for p in parts if p) or "ComfyUI rejected the prompt."


def _format_execution_error(status: Dict[str, Any]) -> str:
    for name, data in status.get("messages", []):
        if name == "execution_error":
            return (
                f"{data.get('node_type', 'node')} {data.get('node_id', '?')}: "
                f"{data.get('exception_message', 'execution failed')}".strip()
            )
    return "ComfyUI reported an execution error."


# Friendly names for the nodes in our graph, used for progress messages.
NODE_LABELS = {
    "15": "Loading checkpoint",
    "27": "Applying LoRAs",
    "10": "Encoding prompt",
    "11": "Encoding negative prompt",
    "32": "Loading source image",
    "30": "Encoding source image",
    "36": "Batching latents",
    "13": "Preparing latent",
    "12": "Sampling",
    "14": "Decoding image",
    "7": "Saving image",
}
PROGRESS_MIN_INTERVAL_SECONDS = 0.3
WS_CONNECT_WAIT_SECONDS = 2.0


def progress_message(
    event: Dict[str, Any],
    state: Dict[str, Any],
    prompt_id: Optional[str] = None,
    now: Optional[float] = None,
) -> Optional[str]:
    """
    Turn one ComfyUI websocket event into a short status line, or None.
    `state` is per-run scratch space (which node is running, throttling, ...).
    """
    etype = event.get("type")
    data = event.get("data") or {}

    pid = data.get("prompt_id")
    if pid and prompt_id and pid != prompt_id:
        return None

    if etype == "status":
        remaining = ((data.get("status") or {}).get("exec_info") or {}).get("queue_remaining")
        if isinstance(remaining, int) and remaining > 1 and not state.get("started"):
            return f"Queued: {remaining - 1} job(s) ahead of this one"
        return None

    if etype == "execution_start":
        state["started"] = True
        return "Starting..."

    if etype == "executing":
        node = data.get("node")
        if node is None:  # end-of-run marker
            return None
        state["started"] = True
        state["node"] = str(node)
        label = NODE_LABELS.get(str(node))
        return f"{label}..." if label else None

    if etype == "progress":
        value, maximum = data.get("value"), data.get("max")
        if not (isinstance(value, int) and isinstance(maximum, int) and maximum > 0):
            return None
        state["started"] = True
        t = time.monotonic() if now is None else now
        if value < maximum and t - state.get("last_progress", float("-inf")) < PROGRESS_MIN_INTERVAL_SECONDS:
            return None  # throttle; the final step always goes through
        state["last_progress"] = t
        node = str(data.get("node") or state.get("node") or "")
        label = NODE_LABELS.get(node, "Working")
        return f"{label}: step {value}/{maximum} ({round(100 * value / maximum)}%)"

    return None


class ComfyClient:
    def __init__(self, base_url: str, timeout: int):
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.lookup_error: Optional[str] = None

    def submit_prompt(self, workflow: Dict[str, Any], client_id: str) -> Dict[str, Any]:
        """POST /prompt. Returns ComfyUI's response ({'prompt_id', 'number', 'node_errors'})."""
        try:
            r = requests.post(
                f"{self.base_url}/prompt",
                json={"prompt": workflow, "client_id": client_id},
                timeout=self.timeout,
            )
        except RequestException as e:
            raise ComfyError(f"Cannot reach ComfyUI at {self.base_url}: {e}") from e
        if r.status_code != 200:
            try:
                body = r.json()
            except ValueError:
                body = {"error": r.text[:500]}
            raise ComfyError(_format_prompt_error(body), body=body)
        return r.json()

    def queue_prompt(self, workflow: Dict[str, Any], client_id: str) -> str:
        return self.submit_prompt(workflow, client_id)["prompt_id"]

    def jobs_ahead(self, number: Any) -> Optional[int]:
        """
        How many jobs (including a running one) were queued before ours.
        Best effort: None if the server's /queue can't be read.
        """
        if not isinstance(number, int):
            return None
        try:
            r = requests.get(f"{self.base_url}/queue", timeout=self.timeout)
            r.raise_for_status()
            q = r.json()
            items = list(q.get("queue_running", [])) + list(q.get("queue_pending", []))
            return sum(
                1
                for it in items
                if isinstance(it, (list, tuple)) and it and isinstance(it[0], int) and it[0] < number
            )
        except (RequestException, ValueError, AttributeError, TypeError):
            return None

    def list_checkpoints(self) -> List[str]:
        """
        Checkpoint filenames the server knows about. Best effort: returns [] if
        the server can't tell us, and records why in self.lookup_error.
        """
        self.lookup_error = None
        try:
            r = requests.get(f"{self.base_url}/object_info/CheckpointLoaderSimple", timeout=self.timeout)
            r.raise_for_status()
            spec = r.json()["CheckpointLoaderSimple"]["input"]["required"]["ckpt_name"]
            names: List[str] = []
            if isinstance(spec[0], list):
                names = [str(x) for x in spec[0]]
            elif spec[0] == "COMBO" and len(spec) > 1:  # newer ComfyUI schema
                names = [str(x) for x in spec[1].get("options", [])]
            if not names:
                self.lookup_error = "server returned no checkpoint list in a format this tool understands"
            return names
        except (RequestException, KeyError, IndexError, TypeError, ValueError) as e:
            self.lookup_error = f"{type(e).__name__}: {e}"
            logger.warning("Could not list checkpoints on %s: %s", self.base_url, self.lookup_error)
        return []

    def get_history(self, prompt_id: str) -> Optional[Dict[str, Any]]:
        try:
            r = requests.get(f"{self.base_url}/history/{prompt_id}", timeout=self.timeout)
            r.raise_for_status()
            return r.json().get(prompt_id)
        except RequestException as e:
            raise ComfyError(f"Lost contact with ComfyUI while waiting: {e}") from e

    def view_url(self, image: Dict[str, Any]) -> str:
        query = urllib.parse.urlencode(
            {
                "filename": image["filename"],
                "subfolder": image.get("subfolder", ""),
                "type": image.get("type", "output"),
            }
        )
        return f"{self.base_url}/view?{query}"

    def fetch_image(self, image: Dict[str, Any]) -> bytes:
        try:
            r = requests.get(self.view_url(image), timeout=self.timeout)
            r.raise_for_status()
            return r.content
        except RequestException as e:
            raise ComfyError(f"Could not download {image['filename']}: {e}") from e

    def upload_image(
        self, image_bytes: bytes, filename: str, subfolder: str = "", type_: str = "output"
    ) -> Dict[str, str]:
        """POST /upload/image. `type_` picks which folder ('input' or 'output') it lands in."""
        try:
            r = requests.post(
                f"{self.base_url}/upload/image",
                files={"image": (filename, image_bytes, mimetypes.guess_type(filename)[0] or "image/png")},
                data={"subfolder": subfolder, "type": type_, "overwrite": "true"},
                timeout=self.timeout,
            )
            r.raise_for_status()
            data = r.json()
        except RequestException as e:
            raise ComfyError(f"Could not upload {filename} to {self.base_url}: {e}") from e
        except ValueError as e:
            raise ComfyError(f"Unexpected upload response from {self.base_url}: {e}") from e
        return {
            "filename": data.get("name", filename),
            "subfolder": data.get("subfolder", subfolder),
            "type": data.get("type", type_),
        }

    async def _listen_progress(
        self,
        client_id: str,
        prompt_box: Dict[str, Optional[str]],
        on_status: Callable[[str], Any],
        connected: asyncio.Event,
    ) -> None:
        """
        Best-effort: relay ComfyUI's websocket progress events as status lines.
        Never raises - completion is still detected by polling /history.
        """
        try:
            import aiohttp  # ships with Open WebUI
        except ImportError:
            connected.set()
            return

        ws_url = f"{self.base_url.replace('http', 'ws', 1)}/ws?clientId={client_id}"
        state: Dict[str, Any] = {}
        try:
            timeout = aiohttp.ClientTimeout(total=None, sock_connect=self.timeout)
            async with aiohttp.ClientSession(timeout=timeout) as session:
                async with session.ws_connect(ws_url, max_msg_size=16 * 1024 * 1024) as ws:
                    connected.set()
                    async for msg in ws:
                        if msg.type in (aiohttp.WSMsgType.CLOSED, aiohttp.WSMsgType.ERROR):
                            break
                        if msg.type != aiohttp.WSMsgType.TEXT:
                            continue  # binary frames are latent previews
                        try:
                            event = json.loads(msg.data)
                        except ValueError:
                            continue
                        text = progress_message(event, state, prompt_box.get("id"))
                        if text:
                            await on_status(text)
        except asyncio.CancelledError:
            raise
        except Exception as e:  # progress is a nicety, never a failure
            logger.debug("Progress websocket unavailable on %s: %s", self.base_url, e)
        finally:
            connected.set()

    async def run(
        self,
        workflow: Dict[str, Any],
        max_wait: int,
        on_status: Optional[Callable[[str], Any]] = None,
        show_progress: bool = True,
        job_uuid: Optional[str] = None,
        db_path: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Queue the workflow and wait for it. Returns {'prompt_id', 'images', 'history'}.
        If job_uuid and db_path are given, records every stage (submitted, completed, or
        failed/rejected at the correct stage) into the job database as it happens.
        """
        client_id = str(uuid.uuid4())
        prompt_box: Dict[str, Optional[str]] = {"id": None}

        # Connect the progress socket *before* queuing so early events aren't missed.
        listener: Optional["asyncio.Task[None]"] = None
        if on_status and show_progress:
            connected = asyncio.Event()
            listener = asyncio.create_task(self._listen_progress(client_id, prompt_box, on_status, connected))
            try:
                await asyncio.wait_for(connected.wait(), timeout=WS_CONNECT_WAIT_SECONDS)
            except asyncio.TimeoutError:
                pass

        try:
            try:
                submit_response = await asyncio.to_thread(self.submit_prompt, workflow, client_id)
            except ComfyError as e:
                if job_uuid and db_path:
                    await asyncio.to_thread(record_job_failed, db_path, job_uuid, "submit", str(e), e.body)
                raise
            prompt_id = submit_response["prompt_id"]
            prompt_box["id"] = prompt_id
            if on_status:
                await on_status(f"Queued on {self.base_url} (prompt {prompt_id[:8]})...")
            if job_uuid and db_path:
                await asyncio.to_thread(record_job_submitted, db_path, job_uuid, prompt_id, submit_response)

            try:
                deadline = time.monotonic() + max_wait
                while True:
                    entry = await asyncio.to_thread(self.get_history, prompt_id)
                    if entry:
                        status = entry.get("status", {})
                        if status.get("status_str") == "error":
                            raise ComfyError(_format_execution_error(status))
                        if status.get("completed") or entry.get("outputs"):
                            break
                    if time.monotonic() > deadline:
                        raise ComfyError(
                            f"Timed out after {max_wait}s (prompt {prompt_id} may still be running on the server)."
                        )
                    await asyncio.sleep(POLL_INTERVAL_SECONDS)
            except ComfyError as e:
                if job_uuid and db_path:
                    await asyncio.to_thread(record_job_failed, db_path, job_uuid, "wait", str(e))
                raise
        finally:
            if listener:
                listener.cancel()
                # return_exceptions=True absorbs the listener's own CancelledError
                # without hiding a cancellation of the surrounding call.
                await asyncio.gather(listener, return_exceptions=True)

        images = [
            img
            for img in entry.get("outputs", {}).get(SAVE_NODE_ID, {}).get("images", [])
            if img.get("type", "output") == "output"
        ]
        if not images:
            if job_uuid and db_path:
                await asyncio.to_thread(record_job_failed, db_path, job_uuid, "wait", "Workflow finished but produced no images.")
            raise ComfyError("Workflow finished but produced no images.")
        if job_uuid and db_path:
            await asyncio.to_thread(record_job_completed, db_path, job_uuid, entry)
        return {"prompt_id": prompt_id, "images": images, "history": entry}



def upload_to_open_webui(
    base_url: str, api_key: str, image_bytes: bytes, filename: str, timeout: int
) -> "tuple[Optional[str], Optional[str]]":
    """
    Store an image in Open WebUI's own file storage via its REST API so the
    browser only ever needs to reach Open WebUI itself (works through
    Tailscale / any reverse proxy, no mixed-content problems).

    Returns (relative_url, None) on success or (None, error_text) on failure.
    The relative URL resolves against whatever host the browser is using.
    """
    if not api_key:
        return None, "OPEN_WEBUI_API_KEY is empty in the tool's valves"
    try:
        resp = requests.post(
            f"{base_url.rstrip('/')}/api/v1/files/",
            headers={"Authorization": f"Bearer {api_key}"},
            files={"file": (filename, image_bytes, mimetypes.guess_type(filename)[0] or "image/png")},
            # Images have no text to extract/embed; skipping Open WebUI's RAG
            # processing avoids a pointless (and error-logging) background job.
            # Older versions simply ignore the parameter.
            params={"process": "false"},
            timeout=timeout,
        )
        resp.raise_for_status()
        file_id = resp.json().get("id")
        if not file_id:
            return None, f"upload response had no 'id' field: {str(resp.text)[:200]}"
        return f"/api/v1/files/{file_id}/content", None
    except RequestException as e:
        detail = ""
        response = getattr(e, "response", None)
        if response is not None:
            detail = f" (HTTP {response.status_code}: {str(response.text)[:200]})"
        return None, f"{e}{detail}"
    except ValueError as e:  # non-JSON response
        return None, f"unexpected response from Open WebUI: {e}"



async def copy_source_image(
    source_server: str, target_client: "ComfyClient", subfolder: str, filename: str, timeout: int
) -> None:
    """Download filename from source_server's output folder and upload it into target_client's."""
    src = ComfyClient(source_server, timeout)
    image = {"filename": filename, "subfolder": subfolder, "type": "output"}
    data = await asyncio.to_thread(src.fetch_image, image)
    await asyncio.to_thread(target_client.upload_image, data, filename, subfolder, "output")


