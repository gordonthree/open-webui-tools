# A separate, dedicated logger for completed-render records (distinct from the
# module logger above, which is for the tool's own diagnostics). Handlers are
# cached per configuration so re-entering generate_image never adds duplicate
# handlers and doesn't duplicate log lines.
_job_logger_cache: Dict[tuple, logging.Logger] = {}


def get_job_logger(v: Any) -> logging.Logger:
    key = (
        v.LOG_BACKEND, v.SYSLOG_ADDRESS, v.SYSLOG_IDENT,
        v.JOB_LOG_PATH, v.JOB_LOG_MAX_BYTES, v.JOB_LOG_BACKUP_COUNT,
    )
    cached = _job_logger_cache.get(key)
    if cached is not None:
        return cached

    job_logger = logging.getLogger(f"comfy_sdxl_direct.jobs.{abs(hash(key))}")
    job_logger.setLevel(logging.INFO)
    job_logger.propagate = False  # keep job records out of the container's general log stream

    wired_syslog = False
    if v.LOG_BACKEND in ("syslog", "both"):
        try:
            handler = logging.handlers.SysLogHandler(address=v.SYSLOG_ADDRESS)
            handler.setFormatter(logging.Formatter(f"{v.SYSLOG_IDENT}: %(message)s"))
            job_logger.addHandler(handler)
            wired_syslog = True
        except OSError as e:
            # Common in containers where /dev/log isn't the host's journald socket.
            logger.warning("Job log: could not open syslog socket %s: %s", v.SYSLOG_ADDRESS, e)

    # Always have a file: it's the explicit backend, or the fallback when syslog didn't wire up.
    if v.LOG_BACKEND in ("file", "both") or not wired_syslog:
        try:
            path = Path(v.JOB_LOG_PATH)
            path.parent.mkdir(parents=True, exist_ok=True)
            handler = logging.handlers.RotatingFileHandler(
                path, maxBytes=v.JOB_LOG_MAX_BYTES, backupCount=v.JOB_LOG_BACKUP_COUNT
            )
            handler.setFormatter(logging.Formatter("%(message)s"))
            job_logger.addHandler(handler)
        except OSError as e:
            logger.warning("Job log: could not open log file %s: %s", v.JOB_LOG_PATH, e)

    _job_logger_cache[key] = job_logger
    return job_logger


def log_completed_job(v: Any, record: Dict[str, Any]) -> None:
    """Best effort: a completed render is never held up or failed by logging trouble."""
    if not v.LOG_JOBS:
        return
    try:
        line = json.dumps({"timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(), **record}, default=str)
        get_job_logger(v).info(line)
    except Exception as e:
        logger.warning("Job log: could not record completed job: %s", e)


# --------------------------------------------------------------------------- #
# SQLite job database - a queryable, verbatim record of every job attempt,
# alongside the syslog/file log above. Design:
#   - job_uuid is generated by the tool BEFORE any network call, so a job that
#     ComfyUI rejects or never responds to is still fully catalogued.
#   - jobs.comfy_prompt_id is filled in once/if the server assigns one, giving
#     a durable link between our id and the server's; it can stay NULL forever
#     for a job the server never saw. comfy_sdxl_retrieve.py's reconciliation
#     logic can backfill it later by matching the 'outputs' graph against a
#     history entry found by filename, for a job that appears server-side
#     without the tool having recorded the link itself.
#   - inputs/outputs/results/errors keep verbatim JSON; prompts and node_params
#     are the broken-out, queryable (non-JSON) columns.
# Shared schema with comfy_sdxl_graph.py and read/written by comfy_sdxl_retrieve.py;
# keep the three in sync by hand if this schema changes.
# --------------------------------------------------------------------------- #

JOB_DB_SCHEMA = """
CREATE TABLE IF NOT EXISTS jobs (
    job_uuid TEXT PRIMARY KEY,
    comfy_prompt_id TEXT,
    tool TEXT NOT NULL,
    server TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL,
    submitted_at TEXT,
    execution_start_ts INTEGER,
    execution_end_ts INTEGER,
    duration_s REAL
);
CREATE INDEX IF NOT EXISTS idx_jobs_comfy_prompt_id ON jobs(comfy_prompt_id);
CREATE INDEX IF NOT EXISTS idx_jobs_server_status ON jobs(server, status);
CREATE INDEX IF NOT EXISTS idx_jobs_created_at ON jobs(created_at);

CREATE TABLE IF NOT EXISTS inputs (
    job_uuid TEXT PRIMARY KEY REFERENCES jobs(job_uuid),
    raw_json TEXT NOT NULL,
    recorded_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS outputs (
    job_uuid TEXT PRIMARY KEY REFERENCES jobs(job_uuid),
    raw_json TEXT NOT NULL,
    recorded_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS results (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    job_uuid TEXT NOT NULL REFERENCES jobs(job_uuid),
    stage TEXT NOT NULL,
    raw_json TEXT NOT NULL,
    recorded_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_results_job_uuid ON results(job_uuid);

CREATE TABLE IF NOT EXISTS errors (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    job_uuid TEXT NOT NULL REFERENCES jobs(job_uuid),
    stage TEXT NOT NULL,
    message TEXT NOT NULL,
    raw_json TEXT,
    recorded_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_errors_job_uuid ON errors(job_uuid);

CREATE TABLE IF NOT EXISTS prompts (
    job_uuid TEXT PRIMARY KEY REFERENCES jobs(job_uuid),
    positive_prompt TEXT,
    negative_prompt TEXT
);

CREATE TABLE IF NOT EXISTS node_params (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    job_uuid TEXT NOT NULL REFERENCES jobs(job_uuid),
    node_id TEXT NOT NULL,
    class_type TEXT NOT NULL,
    param_name TEXT NOT NULL,
    value_text TEXT,
    value_num REAL
);
CREATE INDEX IF NOT EXISTS idx_node_params_job_uuid ON node_params(job_uuid);
CREATE INDEX IF NOT EXISTS idx_node_params_lookup ON node_params(class_type, param_name, value_text);
"""
PROMPTS_FTS_SCHEMA = "CREATE VIRTUAL TABLE IF NOT EXISTS prompts_fts USING fts5(job_uuid UNINDEXED, positive_prompt, negative_prompt);"

JOB_DB_BUSY_TIMEOUT_S = 5.0
_job_db_schema_ready: set = set()  # db_path values confirmed (this process) to have the schema


def job_db_connect(db_path: str):
    """A short-lived connection with the schema ensured. Caller must close() it."""
    import sqlite3

    Path(db_path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_path, timeout=JOB_DB_BUSY_TIMEOUT_S)
    conn.execute("PRAGMA journal_mode=WAL;")
    if db_path not in _job_db_schema_ready:
        conn.executescript(JOB_DB_SCHEMA)
        try:
            conn.execute(PROMPTS_FTS_SCHEMA)
        except Exception:  # sqlite3.OperationalError if this build lacks FTS5; search falls back to LIKE
            pass
        _job_db_schema_ready.add(db_path)
    return conn


def _now_iso() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def extract_node_params(graph: Dict[str, Any]) -> List[tuple]:
    """(node_id, class_type, param_name, value_text, value_num) for every scalar input in the
    graph. List-typed inputs are links to other nodes (e.g. ["12", 0]), not literal values, and
    are skipped - this only captures the literal parameters actually set on each node."""
    rows = []
    for node_id, node in graph.items():
        class_type = node.get("class_type", "")
        for name, value in (node.get("inputs") or {}).items():
            if isinstance(value, list):  # a link to another node's output, not a literal
                continue
            value_num = value if isinstance(value, (int, float)) and not isinstance(value, bool) else None
            rows.append((str(node_id), str(class_type), str(name), json.dumps(value) if not isinstance(value, str) else value, value_num))
    return rows


def has_prompts_fts(conn) -> bool:
    try:
        conn.execute("SELECT 1 FROM prompts_fts LIMIT 0;")
        return True
    except Exception:
        return False


def record_job_built(
    db_path: str,
    job_uuid: str,
    tool: str,
    server: str,
    input_json: Dict[str, Any],
    output_graph: Dict[str, Any],
    positive_prompt: Optional[str],
    negative_prompt: Optional[str],
) -> None:
    """
    First write for a job, made as soon as the graph is fully built - before it is ever sent
    to ComfyUI. This is what guarantees a job is catalogued even if the server rejects it or
    never responds at all.
    """
    try:
        conn = job_db_connect(db_path)
        try:
            now = _now_iso()
            conn.execute(
                "INSERT INTO jobs (job_uuid, tool, server, status, created_at) VALUES (?, ?, ?, 'built', ?)",
                (job_uuid, tool, server, now),
            )
            conn.execute(
                "INSERT INTO inputs (job_uuid, raw_json, recorded_at) VALUES (?, ?, ?)",
                (job_uuid, json.dumps(input_json, default=str), now),
            )
            conn.execute(
                "INSERT INTO outputs (job_uuid, raw_json, recorded_at) VALUES (?, ?, ?)",
                (job_uuid, json.dumps(output_graph, default=str), now),
            )
            conn.execute(
                "INSERT INTO prompts (job_uuid, positive_prompt, negative_prompt) VALUES (?, ?, ?)",
                (job_uuid, positive_prompt, negative_prompt),
            )
            if has_prompts_fts(conn):
                conn.execute(
                    "INSERT INTO prompts_fts (job_uuid, positive_prompt, negative_prompt) VALUES (?, ?, ?)",
                    (job_uuid, positive_prompt or "", negative_prompt or ""),
                )
            conn.executemany(
                "INSERT INTO node_params (job_uuid, node_id, class_type, param_name, value_text, value_num) VALUES (?, ?, ?, ?, ?, ?)",
                [(job_uuid, *row) for row in extract_node_params(output_graph)],
            )
            conn.commit()
        finally:
            conn.close()
    except Exception as e:
        logger.warning("Job DB: could not record built job %s: %s", job_uuid, e)


def record_job_submitted(db_path: str, job_uuid: str, comfy_prompt_id: str, submit_response: Dict[str, Any]) -> None:
    """Second write: the server accepted the job and assigned it a prompt_id."""
    try:
        conn = job_db_connect(db_path)
        try:
            now = _now_iso()
            conn.execute(
                "UPDATE jobs SET comfy_prompt_id = ?, status = 'queued', submitted_at = ? WHERE job_uuid = ?",
                (comfy_prompt_id, now, job_uuid),
            )
            conn.execute(
                "INSERT INTO results (job_uuid, stage, raw_json, recorded_at) VALUES (?, 'submit_response', ?, ?)",
                (job_uuid, json.dumps(submit_response, default=str), now),
            )
            conn.commit()
        finally:
            conn.close()
    except Exception as e:
        logger.warning("Job DB: could not record submitted job %s: %s", job_uuid, e)


def _execution_timing(history_entry: Dict[str, Any]) -> "tuple[Optional[int], Optional[int], Optional[float]]":
    """(start_ts_ms, end_ts_ms, duration_s), all None if the timestamps aren't present."""
    start_ts = end_ts = None
    for name, data in (history_entry.get("status") or {}).get("messages", []):
        ts = data.get("timestamp") if isinstance(data, dict) else None
        if name == "execution_start" and isinstance(ts, (int, float)):
            start_ts = int(ts)
        elif name in ("execution_success", "execution_error", "execution_interrupted") and isinstance(ts, (int, float)):
            end_ts = int(ts)
    duration = (end_ts - start_ts) / 1000 if start_ts is not None and end_ts is not None else None
    return start_ts, end_ts, duration


def record_job_completed(db_path: str, job_uuid: str, history_entry: Dict[str, Any]) -> None:
    """Final write on success: ComfyUI's history entry, with its own reported timing."""
    try:
        start_ts, end_ts, duration = _execution_timing(history_entry)
        conn = job_db_connect(db_path)
        try:
            now = _now_iso()
            conn.execute(
                "UPDATE jobs SET status = 'completed', execution_start_ts = ?, execution_end_ts = ?, duration_s = ? WHERE job_uuid = ?",
                (start_ts, end_ts, duration, job_uuid),
            )
            conn.execute(
                "INSERT INTO results (job_uuid, stage, raw_json, recorded_at) VALUES (?, 'history', ?, ?)",
                (job_uuid, json.dumps(history_entry, default=str), now),
            )
            conn.commit()
        finally:
            conn.close()
    except Exception as e:
        logger.warning("Job DB: could not record completed job %s: %s", job_uuid, e)


def record_job_failed(db_path: str, job_uuid: str, stage: str, message: str, raw_json: Optional[Dict[str, Any]] = None) -> None:
    """
    Final write on failure: rejected by the server (stage='submit'), or accepted but never
    finished (stage='wait' - timeout, lost connection, or an execution_error from the server).
    """
    status = "rejected" if stage == "submit" else "failed"
    try:
        conn = job_db_connect(db_path)
        try:
            now = _now_iso()
            conn.execute("UPDATE jobs SET status = ? WHERE job_uuid = ?", (status, job_uuid))
            conn.execute(
                "INSERT INTO errors (job_uuid, stage, message, raw_json, recorded_at) VALUES (?, ?, ?, ?, ?)",
                (job_uuid, stage, message, json.dumps(raw_json, default=str) if raw_json is not None else None, now),
            )
            conn.commit()
        finally:
            conn.close()
    except Exception as e:
        logger.warning("Job DB: could not record failed job %s: %s", job_uuid, e)

