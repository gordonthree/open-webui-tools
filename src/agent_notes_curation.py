# --------------------------------------------------------------------------- #
# Too-long retries: a model that keeps sending an over-limit entry without continues=true gets it saved anyway
# --------------------------------------------------------------------------- #

OVERLONG_WINDOW_S = 900.0  # refusals older than this no longer count as "in a row"
_overlong: Dict[tuple, "tuple[int, float]"] = {}  # (author, lowercase note name) -> (too-long refusals so far, when the last one was)
# Kept in memory on purpose: Open WebUI keeps the loaded tool cached until its source changes, so this lasts across calls;
# a restart or a new push merely resets the counts, which only means one more refusal before the automatic save.


def _clock() -> float:
    return time.monotonic()


def _overlong_forget(key: tuple) -> None:
    _overlong.pop(key, None)


def plan_entries(key: tuple, text: Any, continues: Any, max_parts: int, auto_after: int) -> List[str]:
    """The entries to save for create/append.

    continues=true, or a text that fits one entry: as entry_parts. A text over the limit sent without continues=true is refused
    as usual (validate_text's message: shorten it, or pass continues=true) until it has been sent that way auto_after times in a
    row (the same author and note, each within OVERLONG_WINDOW_S of the last); that call is then saved as if continues=true had
    been passed. auto_after 0 never does. The refusal itself never mentions this: the character limit is meant to push models
    towards concise notes, and the fallback is only so one that really can't shorten a text isn't stuck."""
    if _to_bool(continues):
        return entry_parts(text, True, max_parts)
    cleaned = strip_leading_date(str(text or "").strip())
    if len(cleaned) <= NOTE_TEXT_MAX:
        return [validate_text(text)]
    try:
        parts = split_text(cleaned, max_parts)
    except NoteError:
        parts = None  # too long even split up (MAX_CONTINUATION_ENTRIES): refused as usual, and not counted
    if parts is not None:
        now = _clock()
        for k, (_, last) in list(_overlong.items()):
            if now - last > OVERLONG_WINDOW_S:
                del _overlong[k]
        attempt = _overlong.get(key, (0, now))[0] + 1
        if auto_after > 0 and attempt >= auto_after:
            logger.info("agent_notes: %r sent a too-long entry for note %r %d times in a row; saved it as %d linked entries", key[0], key[1], attempt, len(parts))
            return parts
        _overlong[key] = (attempt, now)
    validate_text(text)  # raises the usual too-long refusal
    raise AssertionError("unreachable: validate_text refuses any text over the limit")


def parse_entry_numbers(value: Any, cap: int = 10) -> Optional[List[int]]:
    """Entry numbers from "12", "#12" or "12, 15 17" (at most `cap`), or None when nothing was given."""
    if is_unset(value):
        return None
    numbers = [int(x) for x in re.findall(r"\d+", str(value))]
    if not numbers:
        raise NoteError(f'entry must be one or more entry numbers, such as 12 or "12, 15", got {value!r}.')
    return list(dict.fromkeys(numbers))[:cap]


def flag_default_true(value: Any) -> bool:
    """An optional true/false that means true unless it clearly says no (models pass "" for 'default')."""
    return not (value is False or (isinstance(value, str) and value.strip().lower() in {"false", "0", "no", "n", "off"}))


def make_snippet(text: str, words: List[str], width: int) -> str:
    """At most `width` characters of the entry, whitespace collapsed, starting a little before the first word that matched."""
    flat = " ".join((text or "").split())
    if len(flat) <= width:
        return flat
    hit = min((i for i in (flat.lower().find(w) for w in words) if i >= 0), default=0)
    start = 0 if hit < width // 3 else flat.rfind(" ", 0, hit - width // 3) + 1
    piece = flat[start:start + width].rstrip()
    return ("\N{HORIZONTAL ELLIPSIS}" if start else "") + piece + ("\N{HORIZONTAL ELLIPSIS}" if start + width < len(flat) else "")


def fit_entries(groups: List[List[Any]], budget: int) -> List[List[Any]]:
    """Keep whole entries, in the order given (each group's list is already in preference order, groups interleave one entry at a
    time), until the character budget is used; always at least the first entry. Returns the kept entries per group."""
    kept: List[List[Any]] = [[] for _ in groups]
    used = 0
    for rank in range(max((len(g) for g in groups), default=0)):
        for index, group in enumerate(groups):
            if rank < len(group):
                cost = len(group[rank]["note_text"]) + 60
                if used + cost > budget and used > 0:
                    return kept
                used += cost
                kept[index].append(group[rank])
    return kept


