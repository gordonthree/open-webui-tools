#!/usr/bin/env python3
"""
Generate the two deployable Open WebUI tools from src/agent_notes_full.py, which stays the single source of
truth (the database layer, the validation and every tool method live there, and the tests exercise it):

    src/agent_notes.py           "Agent Notes": what a conversational model needs - find, read, write, rate
    src/agent_notes_curation.py  "Agent Notes Curation": tags, summaries, renaming and deleting

Each model is sent every enabled tool's descriptions on every turn, so a small-context model that doesn't curate
shouldn't pay for the curation methods. The generated files are complete, self-contained tool files (Open WebUI
can't import siblings), carrying the whole database layer, with the other tool's methods and valves cut out.
Edit agent_notes_full.py, never the generated files: `python3 scripts/build_agent_notes.py` regenerates them and
`--check` exits 1 if either is stale (src/test_agent_notes_split.py runs that check).
"""
import argparse
import ast
import re
import sys
from pathlib import Path

SRC_DIR = Path(__file__).resolve().parent.parent / "src"
SOURCE = SRC_DIR / "agent_notes_full.py"

CORE_METHODS = [
    "agent_notes_help", "agent_notes_list", "agent_notes_list_tags", "agent_notes_search", "agent_notes_search_summary",
    "agent_notes_read", "agent_notes_read_tagged", "agent_notes_create", "agent_notes_append", "agent_notes_edit_entry",
    "agent_notes_set_weight", "agent_notes_rank_entries",
]
CURATION_METHODS = [
    "agent_notes_add_tags", "agent_notes_remove_tag", "agent_notes_rename_tag", "agent_notes_update", "agent_notes_update_summary",
    "agent_notes_delete_summary", "agent_notes_delete", "agent_notes_delete_entry", "agent_notes_reset_hits",
]

# Tools methods that aren't tool methods (no agent_notes_ prefix) and only one variant uses
PRIVATE_CORE_ONLY = ["_count_reads"]

CORE_DESCRIPTION = """A persistent notebook for agents, easier to use than Open WebUI's built-in note tool.
    A note is a name plus an append-only log of short numbered entries (500 characters each), kept
    in its own SQLite database. To add to a note, append an entry - nothing is ever rewritten or
    diffed. Notes are addressed by their plain-language name, entries by their number.
    This is the everyday tool: agent_notes_list/agent_notes_search/agent_notes_read find and read notes,
    agent_notes_create/agent_notes_append/agent_notes_edit_entry write them, agent_notes_set_weight rates an entry and
    agent_notes_rank_entries picks entries by popularity or weight. agent_notes_help explains it all in short guides.
    Tagging, summaries, renaming and deleting are in the separate Agent Notes Curation tool, which uses the same database.
    Every note and entry records its author (pass author_name, or the tool uses the calling model's name).
    Limits: note name 60 characters, note comment 500, each entry's text 500; longer text needs continues=true,
    which saves it verbatim as several linked entries."""

CURATION_DESCRIPTION = """The upkeep half of Agent Notes (it needs the Agent Notes tool too, and the same NOTES_DB_PATH valve):
    tags (agent_notes_add_tags/agent_notes_remove_tag/agent_notes_rename_tag), summaries
    (agent_notes_update_summary/agent_notes_delete_summary), renaming a note or changing its comment
    (agent_notes_update), resetting read counts (agent_notes_reset_hits), and permanent deletes
    (agent_notes_delete_entry/agent_notes_delete). Meant for a curating or summarizing agent rather than an
    everyday conversational model, so those models don't carry its descriptions in their context."""

VARIANTS = {
    "agent_notes": {"title": "Agent Notes", "description": CORE_DESCRIPTION, "methods": CORE_METHODS, "valves": None, "drop_private": []},
    "agent_notes_curation": {
        "title": "Agent Notes Curation", "description": CURATION_DESCRIPTION, "methods": CURATION_METHODS,
        "valves": ["NOTES_DB_PATH", "DEFAULT_AUTHOR"], "drop_private": PRIVATE_CORE_ONLY,
    },
}

GENERATED_NOTE = "# GENERATED by scripts/build_agent_notes.py from src/agent_notes_full.py - edit that file, then rebuild; not this one.\n"


def _frontmatter(source: str, key: str) -> str:
    m = re.search(rf"^{key}:\s*(.+)$", source, re.M)
    if not m:
        sys.exit(f"{SOURCE.name} has no '{key}:' line in its header.")
    return m.group(1).strip()


def build(source: str, name: str) -> str:
    """The text of the generated tool file for one variant."""
    spec = VARIANTS[name]
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    doc_node = tree.body[0]
    assert isinstance(doc_node, ast.Expr) and isinstance(doc_node.value, ast.Constant), "module docstring expected first"
    tools = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Tools")

    cuts = []  # (first line, last line), 1-based inclusive
    all_methods = set(CORE_METHODS) | set(CURATION_METHODS)
    for node in tools.body:
        if isinstance(node, (ast.AsyncFunctionDef, ast.FunctionDef)):
            drop = (node.name in all_methods and node.name not in spec["methods"]) or node.name in spec["drop_private"]
            if drop:
                end = node.end_lineno + (1 if lines[node.end_lineno:node.end_lineno + 1] == ["\n"] else 0)  # and the blank line after it
                first = min([node.lineno] + [d.lineno for d in node.decorator_list])  # a decorator belongs to the method it decorates
                cuts.append((first, end))
        elif isinstance(node, ast.ClassDef) and node.name == "Valves" and spec["valves"] is not None:
            for field in node.body:
                if isinstance(field, ast.AnnAssign) and field.target.id not in spec["valves"]:
                    cuts.append((field.lineno, field.end_lineno))
    present = {n.name for n in tools.body if isinstance(n, (ast.AsyncFunctionDef, ast.FunctionDef)) and n.name.startswith("agent_notes_")}
    if present != all_methods:
        sys.exit(f"Every tool method must belong to one variant: unassigned {sorted(present - all_methods)}, missing from source {sorted(all_methods - present)}.")

    for first, last in sorted(cuts, reverse=True):
        del lines[first - 1:last]
    body = "".join(lines[doc_node.end_lineno:])  # everything after the module docstring (line numbers before it are untouched)
    header = (
        f'"""\ntitle: {spec["title"]}\nauthor: {_frontmatter(source, "author")}\nversion: {_frontmatter(source, "version")}\n'
        f'description: {spec["description"]}\n"""\n{GENERATED_NOTE}'
    )
    return header + body


def targets() -> dict:
    return {SRC_DIR / f"{name}.py": name for name in VARIANTS}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Write nothing; exit 1 if a generated file is out of date.")
    args = parser.parse_args()
    source = SOURCE.read_text(encoding="utf-8")
    stale = []
    for path, name in targets().items():
        text = build(source, name)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            print(f"{path.name}: up to date")
        elif args.check:
            stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"{path.name}: written ({len(text)} bytes)")
    if stale:
        sys.exit(f"Out of date: {', '.join(stale)} - run python3 scripts/build_agent_notes.py")


if __name__ == "__main__":
    main()
